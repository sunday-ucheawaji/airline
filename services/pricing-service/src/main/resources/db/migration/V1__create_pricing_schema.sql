-- Baseline schema for pricing-service, as of step 5 (exact money with currency, sales and travel windows,
-- natural-key uniqueness, search index). Later steps edit this file in place, as with every other service's V1,
-- since dev databases are recreated rather than altered.

CREATE TABLE IF NOT EXISTS fares (
    id                          BIGINT AUTO_INCREMENT PRIMARY KEY,
    -- Cross-service ref: Airline is in airline-core-service, no FK. Set from flight-ops at creation.
    airline_id                  BIGINT NOT NULL,
    -- Cross-service ref: Flight is in flight-ops-service, no FK. The route template, not a departure.
    flight_id                   BIGINT NOT NULL,
    -- Cross-service ref: CabinClass is in seat-service, no FK. Informational only (changes with the aircraft).
    cabin_class_id              BIGINT NOT NULL,
    cabin_class                 ENUM('ECONOMY','PREMIUM_ECONOMY','BUSINESS','FIRST') NOT NULL,
    passenger_type              ENUM('ADT','CHD','INF') NOT NULL,
    rbd_code                    VARCHAR(1) NOT NULL,
    fare_basis_code             VARCHAR(20),
    name                        VARCHAR(255) NOT NULL,
    fare_label                  VARCHAR(100),
    status                      ENUM('DRAFT','PUBLISHED','WITHDRAWN') NOT NULL,
    currency                    VARCHAR(3) NOT NULL,
    base_fare                   DECIMAL(12,2) NOT NULL,
    taxes_and_fees              DECIMAL(12,2),
    airline_fees                DECIMAL(12,2),
    total_amount                DECIMAL(12,2) NOT NULL,
    sales_from                  DATETIME(6) NOT NULL,
    sales_to                    DATETIME(6) NOT NULL,
    travel_from                 DATE NOT NULL,
    travel_to                   DATE NOT NULL,
    advance_purchase_days       INT,
    extra_seat_space            BIT(1) NOT NULL,
    preferred_seat_choice       BIT(1) NOT NULL,
    advance_seat_selection      BIT(1) NOT NULL,
    guaranteed_seat_together    BIT(1) NOT NULL,
    priority_boarding           BIT(1) NOT NULL,
    priority_checkin            BIT(1) NOT NULL,
    fast_track_security         BIT(1) NOT NULL,
    complimentary_meals         BIT(1) NOT NULL,
    premium_meal_choice         BIT(1) NOT NULL,
    in_flight_internet          BIT(1) NOT NULL,
    in_flight_entertainment     BIT(1) NOT NULL,
    complimentary_beverages     BIT(1) NOT NULL,
    free_date_change            BIT(1) NOT NULL,
    partial_refund              BIT(1) NOT NULL,
    full_refund                 BIT(1) NOT NULL,
    lounge_access               BIT(1) NOT NULL,
    airport_transfer            BIT(1) NOT NULL,
    version                     BIGINT NOT NULL DEFAULT 0,
    created_by                  BIGINT,
    updated_by                  BIGINT,
    created_at                  DATETIME(6) NOT NULL,
    updated_at                  DATETIME(6) NOT NULL,
    CONSTRAINT uk_fares_natural_key UNIQUE (airline_id, flight_id, cabin_class, rbd_code, passenger_type, name),
    INDEX idx_fares_airline_id (airline_id),
    INDEX idx_fares_search (flight_id, cabin_class, status, travel_from, travel_to),
    CONSTRAINT chk_fares_sales_window CHECK (sales_from <= sales_to),
    CONSTRAINT chk_fares_travel_window CHECK (travel_from <= travel_to),
    CONSTRAINT chk_fares_advance_purchase CHECK (advance_purchase_days IS NULL OR advance_purchase_days >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fare_rules (
    id                      BIGINT AUTO_INCREMENT PRIMARY KEY,
    fare_id                 BIGINT NOT NULL UNIQUE,
    rule_name               VARCHAR(255),
    -- Cross-service ref: Airline is in airline-core-service, no FK. Copied from the fare.
    airline_id              BIGINT NOT NULL,
    is_refundable           BIT(1),
    change_fee              DOUBLE,
    cancellation_fee        DOUBLE,
    refund_deadline_days    INT,
    change_deadline_hours   INT,
    is_changeable           BIT(1),
    version                 BIGINT NOT NULL DEFAULT 0,
    created_by              BIGINT,
    updated_by              BIGINT,
    created_at              DATETIME(6),
    updated_at              DATETIME(6),
    INDEX idx_fare_rules_airline_id (airline_id),
    CONSTRAINT fk_fare_rules_fare FOREIGN KEY (fare_id) REFERENCES fares (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS baggage_policies (
    id                                  BIGINT AUTO_INCREMENT PRIMARY KEY,
    fare_id                             BIGINT NOT NULL UNIQUE,
    name                                VARCHAR(255) NOT NULL,
    description                         VARCHAR(255),
    -- Cross-service ref: Airline is in airline-core-service, no FK. Copied from the fare.
    airline_id                          BIGINT NOT NULL,
    version                             BIGINT NOT NULL DEFAULT 0,
    created_by                          BIGINT,
    updated_by                          BIGINT,
    cabin_baggage_max_weight            DOUBLE,
    cabin_baggage_pieces                INT,
    cabin_baggage_weight_per_piece      DOUBLE,
    cabin_baggage_max_dimension         DOUBLE,
    check_in_baggage_max_weight         DOUBLE,
    check_in_baggage_pieces             INT,
    check_in_baggage_weight_per_piece   DOUBLE,
    free_checked_bags_allowance         INT,
    priority_baggage                    BIT(1) NOT NULL,
    extra_baggage_allowance             BIT(1) NOT NULL,
    created_at                          DATETIME(6) NOT NULL,
    updated_at                          DATETIME(6) NOT NULL,
    INDEX idx_baggage_policies_airline_id (airline_id),
    CONSTRAINT fk_baggage_policies_fare FOREIGN KEY (fare_id) REFERENCES fares (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
